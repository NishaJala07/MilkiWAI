package com.example.milkiwai.utils.pdf

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import android.os.Environment
import com.example.milkiwai.data.entity.BillItemWithBrand
import com.example.milkiwai.data.entity.Customer
import com.example.milkiwai.data.entity.MonthlyBill
import java.io.File
import java.io.FileOutputStream
import java.text.DateFormatSymbols

class PdfGenerator(private val context: Context) {

    fun generateBillPdf(
        customer: Customer,
        bill: MonthlyBill,
        items: List<BillItemWithBrand>
    ): String {
        val pdfDocument = PdfDocument()
        val paint = Paint()
        val titlePaint = Paint()

        // Page description
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // A4 Size
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        // Header
        titlePaint.textAlign = Paint.Align.CENTER
        titlePaint.textSize = 24f
        titlePaint.isFakeBoldText = true
        canvas.drawText("Milk Billing System", 297f, 50f, titlePaint)

        // Customer Details
        paint.textSize = 14f
        canvas.drawText("Customer: ${customer.name}", 50f, 100f, paint)
        canvas.drawText("Building: ${customer.buildingName}", 50f, 120f, paint)
        canvas.drawText("Room No: ${customer.roomNo}", 50f, 140f, paint)
        
        val monthName = DateFormatSymbols().months[bill.month - 1]
        canvas.drawText("Month: $monthName ${bill.year}", 50f, 160f, paint)
        canvas.drawText("Bill Date: ${bill.billDate}", 50f, 180f, paint)

        // Table Header
        paint.isFakeBoldText = true
        canvas.drawText("Brand", 50f, 230f, paint)
        canvas.drawText("Quantity", 250f, 230f, paint)
        canvas.drawText("Rate", 350f, 230f, paint)
        canvas.drawText("Amount", 450f, 230f, paint)
        canvas.drawLine(50f, 240f, 550f, 240f, paint)

        // Table Content
        paint.isFakeBoldText = false
        var y = 265f
        for (item in items) {
            canvas.drawText(item.brand?.brandName ?: "Unknown", 50f, y, paint)
            canvas.drawText("${item.billItem.totalQuantity} L", 250f, y, paint)
            canvas.drawText("₹${item.billItem.ratePerLitre}", 350f, y, paint)
            canvas.drawText("₹${item.billItem.amount}", 450f, y, paint)
            y += 25f
        }

        // Grand Total
        canvas.drawLine(50f, y, 550f, y, paint)
        y += 30f
        paint.isFakeBoldText = true
        paint.textSize = 16f
        canvas.drawText("Grand Total: ₹${bill.totalAmount}", 350f, y, paint)

        // Footer
        y += 60f
        paint.textAlign = Paint.Align.CENTER
        paint.textSize = 12f
        paint.isFakeBoldText = false
        canvas.drawText("Thank You", 297f, y, paint)
        canvas.drawText("Generated By Milk Billing System", 297f, y + 20f, paint)

        pdfDocument.finishPage(page)

        // Save file
        val directory = File(context.getExternalFilesDir(Environment.DIRECTORY_DOCUMENTS), "MilkBilling")
        if (!directory.exists()) directory.mkdirs()
        
        val fileName = "Bill_${customer.name.replace(" ", "_")}_${monthName}_${bill.year}.pdf"
        val file = File(directory, fileName)
        
        try {
            pdfDocument.writeTo(FileOutputStream(file))
        } catch (e: Exception) {
            e.printStackTrace()
        } finally {
            pdfDocument.close()
        }

        return file.absolutePath
    }

    fun generateReportPdf(
        title: String,
        headers: List<String>,
        rows: List<List<String>>,
        summary: String = ""
    ): String {
        val pdfDocument = PdfDocument()
        val paint = Paint()
        val titlePaint = Paint()

        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas: Canvas = page.canvas

        titlePaint.textAlign = Paint.Align.CENTER
        titlePaint.textSize = 24f
        titlePaint.isFakeBoldText = true
        canvas.drawText(title, 297f, 50f, titlePaint)

        paint.textSize = 12f
        var y = 100f

        // Draw Headers
        paint.isFakeBoldText = true
        val colWidth = 500f / headers.size
        for (i in headers.indices) {
            canvas.drawText(headers[i], 50f + (i * colWidth), y, paint)
        }
        y += 10f
        canvas.drawLine(50f, y, 550f, y, paint)
        y += 20f

        // Draw Rows
        paint.isFakeBoldText = false
        for (row in rows) {
            for (i in row.indices) {
                canvas.drawText(row[i], 50f + (i * colWidth), y, paint)
            }
            y += 20f
            if (y > 750) break // Very basic page break handling
        }

        if (summary.isNotEmpty()) {
            y += 20f
            paint.isFakeBoldText = true
            canvas.drawText(summary, 50f, y, paint)
        }

        pdfDocument.finishPage(page)

        val directory = File(context.getExternalFilesDir(Environment.DIRECTORY_DOCUMENTS), "MilkBilling/Reports")
        if (!directory.exists()) directory.mkdirs()
        val file = File(directory, "Report_${System.currentTimeMillis()}.pdf")
        
        pdfDocument.writeTo(FileOutputStream(file))
        pdfDocument.close()

        return file.absolutePath
    }
}
