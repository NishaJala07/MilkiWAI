package com.example.milkiwai.ui.delivery

import android.os.Bundle
import android.widget.Button
import android.widget.TextView
import androidx.activity.viewModels
import androidx.appcompat.app.AppCompatActivity
import com.example.milkiwai.R
import com.example.milkiwai.viewmodel.DeliveryViewModel
import java.util.*

class DeliverySummaryActivity : AppCompatActivity() {

    private val viewModel: DeliveryViewModel by viewModels()

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContentView(R.layout.activity_delivery_summary)

        val tvScheduled = findViewById<TextView>(R.id.tvScheduledCount)
        val tvDelivered = findViewById<TextView>(R.id.tvDeliveredCount)
        val tvMissed = findViewById<TextView>(R.id.tvMissedCount)
        val tvSuccessRate = findViewById<TextView>(R.id.tvSuccessRate)

        viewModel.deliveryItems.observe(this) { items ->
            val total = items.size
            val delivered = items.count { it.delivery?.status == "DELIVERED" }
            val missed = items.count { it.delivery?.status == "MISSED" }
            
            tvScheduled.text = total.toString()
            tvDelivered.text = delivered.toString()
            tvMissed.text = missed.toString()
            
            val rate = if (total > 0) (delivered.toDouble() / total * 100) else 0.0
            tvSuccessRate.text = "${String.format("%.1f", rate)}%"
        }

        viewModel.loadDeliveries(Date())

        findViewById<Button>(R.id.btnDone).setOnClickListener { finish() }
        
        findViewById<Button>(R.id.btnShareSummary).setOnClickListener {
            shareDeliverySummary()
        }
    }

    private fun shareDeliverySummary() {
        val items = viewModel.deliveryItems.value ?: return
        val total = items.size
        val delivered = items.count { it.delivery?.status == "DELIVERED" }
        val missed = items.count { it.delivery?.status == "MISSED" }
        val rate = if (total > 0) (delivered.toDouble() / total * 100) else 0.0

        val sdf = java.text.SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
        val summaryText = """
            *Daily Delivery Summary*
            Date: ${sdf.format(Date())}
            -------------------------
            Scheduled: $total
            Delivered: $delivered
            Missed: $missed
            Success Rate: ${String.format("%.1f", rate)}%
            -------------------------
            Generated by MilkiWAI
        """.trimIndent()

        val intent = android.content.Intent(android.content.Intent.ACTION_SEND)
        intent.type = "text/plain"
        intent.putExtra(android.content.Intent.EXTRA_TEXT, summaryText)
        startActivity(android.content.Intent.createChooser(intent, "Share Summary via"))
    }
}
